    // 生成符合 G1-G7 阶梯维度的数学题
    function generateMathProblem(grade, mode) {
        let question = "";
        let answer = "";
        let wrong1 = "", wrong2 = "", wrong3 = "";
        let randInt = (min, max) => Math.floor(Math.random() * (max - min + 1)) + min;

        if (mode === 'ADD_SUB') {
            let isAdd = Math.random() > 0.5;
            if (grade === 1) {
                if (isAdd) {
                    let a = randInt(1, 10), b = randInt(1, 10);
                    question = `${a} + ${b} = ?`;
                    let ans = a + b; answer = String(ans);
                    wrong1 = String(ans + randInt(1, 2)); wrong2 = String(Math.max(1, ans - randInt(1, 2))); wrong3 = String(ans + 3);
                } else {
                    let a = randInt(2, 10), b = randInt(1, a);
                    question = `${a} - ${b} = ?`;
                    let ans = a - b; answer = String(ans);
                    wrong1 = String(ans + 1); wrong2 = String(Math.max(0, ans - 1)); wrong3 = String(ans + 2);
                }
            } else if (grade === 2) {
                if (isAdd) {
                    let a = randInt(10, 50), b = randInt(10, 50);
                    question = `${a} + ${b} = ?`;
                    let ans = a + b; answer = String(ans);
                    wrong1 = String(ans + 10); wrong2 = String(ans - 5); wrong3 = String(ans + 2);
                } else {
                    let a = randInt(20, 99), b = randInt(10, a);
                    question = `${a} - ${b} = ?`;
                    let ans = a - b; answer = String(ans);
                    wrong1 = String(ans + 10); wrong2 = String(Math.max(1, ans - 5)); wrong3 = String(ans + 3);
                }
            } else if (grade <= 4) {
                let a = randInt(100, 500), b = randInt(50, 400);
                if (isAdd) {
                    question = `${a} + ${b} = ?`; answer = String(a + b);
                    wrong1 = String(a + b + 10); wrong2 = String(a + b - 10); wrong3 = String(a + b + 100);
                } else {
                    if (a < b) { let tmp = a; a = b; b = tmp; }
                    question = `${a} - ${b} = ?`; answer = String(a - b);
                    wrong1 = String(a - b + 10); wrong2 = String(Math.max(0, a - b - 10)); wrong3 = String(a - b + 5);
                }
            } else {
                let a = (randInt(100, 999) / 10).toFixed(1);
                let b = (randInt(100, 999) / 10).toFixed(1);
                let numA = parseFloat(a), numB = parseFloat(b);
                if (isAdd) {
                    question = `${a} + ${b} = ?`; answer = (numA + numB).toFixed(1);
                    wrong1 = (numA + numB + 1.1).toFixed(1); wrong2 = (numA + numB - 0.5).toFixed(1); wrong3 = (numA + numB + 2).toFixed(1);
                } else {
                    if (numA < numB) { let tmp = numA; numA = numB; numB = tmp; a = String(numA); b = String(numB); }
                    question = `${a} - ${b} = ?`; answer = (numA - numB).toFixed(1);
                    wrong1 = (numA - numB + 0.5).toFixed(1); wrong2 = Math.max(0, numA - numB - 0.2).toFixed(1); wrong3 = (numA - numB + 1.2).toFixed(1);
                }
            }
        } else if (mode === 'MUL_DIV') {
            let isMul = Math.random() > 0.5;
            if (grade <= 2) {
                let a = randInt(1, 5), b = randInt(1, 5);
                if (isMul) {
                    question = `${a} × ${b} = ?`; answer = String(a * b);
                    wrong1 = String(a * b + a); wrong2 = String(Math.max(1, a * b - 1)); wrong3 = String(a * b + 2);
                } else {
                    let ansVal = randInt(1, 5);
                    let prod = b * ansVal;
                    question = `${prod} ÷ ${b} = ?`; answer = String(ansVal);
                    wrong1 = String(ansVal + 1); wrong2 = String(Math.max(1, ansVal - 1)); wrong3 = String(ansVal + 2);
                }
            } else if (grade <= 4) {
                let a = randInt(2, 9), b = randInt(2, 9);
                if (isMul) {
                    question = `${a} × ${b} = ?`; answer = String(a * b);
                    wrong1 = String(a * b + a); wrong2 = String(Math.max(1, a * b - b)); wrong3 = String(a * b + 4);
                } else {
                    let ansVal = randInt(2, 9);
                    let prod = b * ansVal;
                    question = `${prod} ÷ ${b} = ?`; answer = String(ansVal);
                    wrong1 = String(ansVal + 1); wrong2 = String(Math.max(1, ansVal - 1)); wrong3 = String(ansVal + 2);
                }
            } else {
                if (isMul) {
                    let a = randInt(11, 25), b = randInt(3, 12);
                    question = `${a} × ${b} = ?`; answer = String(a * b);
                    wrong1 = String(a * b + 10); wrong2 = String(a * b - b); wrong3 = String(a * b + a);
                } else {
                    let b = randInt(4, 12), ansVal = randInt(11, 25);
                    let prod = b * ansVal;
                    question = `${prod} ÷ ${b} = ?`; answer = String(ansVal);
                    wrong1 = String(ansVal + 2); wrong2 = String(Math.max(1, ansVal - 2)); wrong3 = String(ansVal + 5);
                }
            }
        } else if (mode === 'FRAC') {
            if (grade <= 2) {
                let num1 = randInt(1, 3);
                question = `${num1}/4 + 1/4 = ?`;
                let ans = num1 + 1;
                answer = `${ans}/4`; wrong1 = `${ans + 1}/4`; wrong2 = `${Math.max(1, ans - 1)}/4`; wrong3 = `${ans}/5`;
            } else if (grade <= 4) {
                let den = randInt(3, 8);
                let num1 = randInt(1, den - 1);
                let num2 = randInt(1, den - num1);
                question = `${num1}/${den} + ${num2}/${den} = ?`;
                let sumNum = num1 + num2;
                answer = `${sumNum}/${den}`; wrong1 = `${sumNum + 1}/${den}`; wrong2 = `${Math.max(1, sumNum - 1)}/${den}`; wrong3 = `${sumNum}/${den + 1}`;
            } else {
                let den1 = 2, den2 = 4;
                if (Math.random() > 0.5) { den1 = 3; den2 = 6; }
                question = `1/${den1} + 1/${den2} = ?`;
                let g = gcd(den1 + den2, den1 * den2);
                let numAns = (den1 + den2) / g;
                let denAns = (den1 * den2) / g;
                answer = `${numAns}/${denAns}`;
                wrong1 = `2/${den1 + den2}`; wrong2 = `1/${den1 + den2}`; wrong3 = `${numAns + 1}/${denAns}`;
            }
        } else if (mode === 'GEO') {
            if (grade <= 2) {
                let type = randInt(1, 3);
                if (mathLang === 'zh') {
                    if (type === 1) { question = "三角形有几条边？"; answer = "3"; wrong1 = "4"; wrong2 = "5"; wrong3 = "6"; }
                    else if (type === 2) { question = "正方形有几条边？"; answer = "4"; wrong1 = "3"; wrong2 = "5"; wrong3 = "2"; }
                    else { question = "五边形有几条边？"; answer = "5"; wrong1 = "4"; wrong2 = "6"; wrong3 = "3"; }
                } else {
                    if (type === 1) { question = "Sides in a triangle?"; answer = "3"; wrong1 = "4"; wrong2 = "5"; wrong3 = "6"; }
                    else if (type === 2) { question = "Sides in a square?"; answer = "4"; wrong1 = "3"; wrong2 = "5"; wrong3 = "2"; }
                    else { question = "Sides in a pentagon?"; answer = "5"; wrong1 = "4"; wrong2 = "6"; wrong3 = "3"; }
                }
            } else if (grade <= 4) {
                let type = randInt(1, 2);
                if (type === 1) {
                    let side = randInt(2, 8);
                    question = mathLang === 'zh' ? `边长为${side}的正方形周长=?` : `Square perim. (side=${side})?`; 
                    answer = String(side * 4);
                    wrong1 = String(side * side); wrong2 = String(side * 2); wrong3 = String(side * 4 + 2);
                } else {
                    let w = randInt(2, 6), h = randInt(2, 6);
                    question = mathLang === 'zh' ? `长${w}宽${h}的长方形面积=?` : `Rect. area (${w}x${h})?`; 
                    answer = String(w * h);
                    wrong1 = String((w + h) * 2); wrong2 = String(w * h + 2); wrong3 = String(w + h);
                }
            } else {
                let type = randInt(1, 2);
                if (type === 1) {
                    let b = randInt(4, 10), h = randInt(2, 8);
                    if (h % 2 !== 0) h++;
                    question = mathLang === 'zh' ? `底${b}高${h}的三角形面积=?` : `Triangle area (b=${b}, h=${h})?`; 
                    answer = String((b * h) / 2);
                    wrong1 = String(b * h); wrong2 = String((b * h) / 2 + 2); wrong3 = String(b + h);
                } else {
                    let a = randInt(30, 80);
                    question = mathLang === 'zh' ? `直角三角形一锐角${a}°，另一角=?` : `Rt. tri. angle (${a}°), other=?`; 
                    answer = String(90 - a);
                    wrong1 = String(180 - a); wrong2 = String(90 + a); wrong3 = String(45);
                }
            }
        }

        let optionsSet = new Set([answer, wrong1, wrong2, wrong3]);
        let optArray = Array.from(optionsSet);
        while(optArray.length < 4) {
            optArray.push(String(randInt(1, 50)));
        }

        return {
            question: question,
            correctAnswer: answer,
            options: optArray
        };
    }

    // --- Shared floating-bubble helpers (Chinese + Math modes) ---
    const FLOAT_LAYOUT = { offScreenX: 60, minGapX: 110, gapFactor: 0.25, yMin: 0.2, yRange: 0.6 };
    function shuffleArray(arr) {
        for (let i = arr.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [arr[i], arr[j]] = [arr[j], arr[i]];
        }
        return arr;
    }

    function spawnFloatingBubbles(rawItems, radius) {
        const items = shuffleArray([...rawItems]);
        const startX = canvas.width + FLOAT_LAYOUT.offScreenX;
        const gapX = Math.max(FLOAT_LAYOUT.minGapX, canvas.width * FLOAT_LAYOUT.gapFactor);
        const bubbleY = getBubbleYRange();
        return items.map((item, i) => {
            const bubble = {
                ...item,
                x: startX + i * gapX,
                y: bubbleY.top + Math.random() * bubbleY.height,
                eaten: false,
                radius
            };
            clampBubbleY(bubble);
            return bubble;
        });
    }

    function relayoutFloatingBubbles(bubbles) {
        const startX = canvas.width + FLOAT_LAYOUT.offScreenX;
        const gapX = Math.max(FLOAT_LAYOUT.minGapX, canvas.width * FLOAT_LAYOUT.gapFactor);
        const bubbleY = getBubbleYRange();
        shuffleArray(bubbles);
        bubbles.forEach((b, i) => {
            b.x = startX + i * gapX;
            b.y = bubbleY.top + Math.random() * bubbleY.height;
            b.eaten = false;
            clampBubbleY(b);
        });
    }

    function drawFloatingBubbles(items, theme) {
        const hudBottom = getPlayingHudBottom();
        for (let item of items) {
            if (item.eaten) continue;
            if (item.y - item.radius < hudBottom) continue;
            ctx.save();
            ctx.translate(item.x, item.y);

            if (theme.type === 'chinese') {
                ctx.fillStyle = "#D90429";
                ctx.beginPath();
                ctx.arc(0, 0, item.radius, 0, Math.PI * 2);
                ctx.fill();
                ctx.strokeStyle = theme.stroke;
                ctx.lineWidth = 3;
                ctx.stroke();
                if (showPinyin && item.pinyin) {
                    ctx.fillStyle = "#FFE66D";
                    ctx.font = "bold 12px sans-serif";
                    ctx.textAlign = "center";
                    ctx.textBaseline = "middle";
                    ctx.fillText(item.pinyin, 0, -13);
                    ctx.fillStyle = "#FFD700";
                    ctx.font = "bold 22px sans-serif";
                    ctx.fillText(item.text, 0, 8);
                } else {
                    ctx.fillStyle = "#FFD700";
                    ctx.font = "bold 24px sans-serif";
                    ctx.textAlign = "center";
                    ctx.textBaseline = "middle";
                    ctx.fillText(item.text, 0, 0);
                }
            } else {
                ctx.fillStyle = "#118AB2";
                ctx.beginPath();
                ctx.arc(0, 0, item.radius, 0, Math.PI * 2);
                ctx.fill();
                ctx.strokeStyle = theme.stroke;
                ctx.lineWidth = 3;
                ctx.stroke();
                ctx.fillStyle = "#FFF";
                ctx.font = "bold 18px sans-serif";
                ctx.textAlign = "center";
                ctx.textBaseline = "middle";
                ctx.fillText(item.text, 0, 0);
            }
            ctx.restore();
        }
    }

