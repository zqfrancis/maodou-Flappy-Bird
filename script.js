    function drawStandardBird(ctx, radius, frames, customBodyColor = "#F8D030") {
        // 1. 身体
        ctx.fillStyle = customBodyColor;
        ctx.beginPath();
        ctx.arc(0, 0, radius, 0, Math.PI * 2);
        ctx.fill();
        ctx.lineWidth = 2;
        ctx.strokeStyle = "#000";
        ctx.stroke();

        // 2. 眼睛（白眼球）
        ctx.fillStyle = "#FFF";
        ctx.beginPath();
        ctx.arc(6, -6, 6, 0, Math.PI * 2);
        ctx.fill();
        ctx.stroke();

        // 3. 瞳孔（黑眼珠）
        ctx.fillStyle = "#000";
        ctx.beginPath();
        ctx.arc(8, -6, 2, 0, Math.PI * 2);
        ctx.fill();

        // 4. 嘴巴
        ctx.fillStyle = "#F05A24";
        ctx.beginPath();
        ctx.arc(8, 4, 8, 0, Math.PI);
        ctx.fill();
        ctx.stroke();

        // 5. 翅膀
        ctx.fillStyle = customBodyColor === "#F8D030" ? "#E0C020" : "#FFB6C1";
        ctx.beginPath();
        let wingY = Math.sin(frames * 0.3) * 3;
        if (ctx.ellipse) {
            ctx.ellipse(-6, wingY, 7, 5, 0, 0, Math.PI * 2);
        } else {
            ctx.arc(-6, wingY, 6, 0, Math.PI * 2);
        }
        ctx.fill();
        ctx.stroke();
    }

